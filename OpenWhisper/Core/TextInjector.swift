import AppKit
import CoreGraphics
import ApplicationServices

final class TextInjector: @unchecked Sendable {

    /// Copy text to the system clipboard
    func copyToClipboard(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    /// Paste text into the target app, then put the user's previous clipboard back.
    func pasteText(_ text: String, targetApp: NSRunningApplication? = nil) {
        // Filter junk
        let cleaned = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if cleaned.isEmpty || cleaned.hasPrefix("[BLANK") {
            owLog("[TextInjector] Skipping empty/junk text: \(cleaned)")
            return
        }

        owLog("[TextInjector] Starting paste (\(cleaned.count) chars)")

        let saved = snapshotClipboard()
        copyToClipboard(cleaned)
        let ourChangeCount = NSPasteboard.general.changeCount

        // Activate the target app
        if let app = targetApp {
            owLog("[TextInjector] Activating: \(app.localizedName ?? "?") (pid \(app.processIdentifier))")
            app.activate()
        }

        // Wait for app to come to front, then paste via CGEvent
        let delay: TimeInterval = 0.5
        DispatchQueue.main.asyncAfter(deadline: .now() + delay) { [self] in
            let frontmost = NSWorkspace.shared.frontmostApplication
            owLog("[TextInjector] Frontmost at paste time: \(frontmost?.localizedName ?? "none") (pid \(frontmost?.processIdentifier ?? 0))")
            self.simulateCmdV()

            // Give the target app time to read the clipboard before restoring it.
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) { [self] in
                // Skip if anything else wrote to the clipboard in the meantime.
                guard NSPasteboard.general.changeCount == ourChangeCount else {
                    owLog("[TextInjector] Clipboard changed since paste — not restoring")
                    return
                }
                self.restoreClipboard(saved)
            }
        }
    }

    // MARK: - Clipboard preservation

    private typealias ClipboardSnapshot = [[NSPasteboard.PasteboardType: Data]]

    /// Markers password managers and other apps set on data that must not linger (nspasteboard.org convention).
    private static let doNotRestoreTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private func snapshotClipboard() -> ClipboardSnapshot {
        let items = NSPasteboard.general.pasteboardItems ?? []
        // A password (or other concealed/transient item) is on the clipboard: never copy it or put it back,
        // or we'd undo the password manager's auto-clear. Empty snapshot = don't restore.
        if items.contains(where: { !Set($0.types).isDisjoint(with: Self.doNotRestoreTypes) }) {
            owLog("[TextInjector] Clipboard holds concealed/transient data — not saving or restoring it")
            return []
        }
        return items.map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { entry[type] = data }
            }
            return entry
        }
    }

    private func restoreClipboard(_ snapshot: ClipboardSnapshot) {
        // Nothing was on the clipboard before: leave the dictated text there.
        guard !snapshot.isEmpty else { return }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        let items = snapshot.map { entry -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entry { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
        owLog("[TextInjector] Restored previous clipboard (\(snapshot.count) item(s))")
    }

    /// Simulate Cmd+V via CGEvent
    private func simulateCmdV() {
        let vKeyCode: CGKeyCode = 9

        guard let keyDown = CGEvent(keyboardEventSource: nil, virtualKey: vKeyCode, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: nil, virtualKey: vKeyCode, keyDown: false) else {
            owLog("[TextInjector] CGEvent creation failed!")
            return
        }

        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand

        keyDown.post(tap: .cghidEventTap)
        usleep(80_000)
        keyUp.post(tap: .cghidEventTap)
        owLog("[TextInjector] CGEvent Cmd+V posted")
    }
}
